#!/usr/bin/env python3
"""Render a generated dataset's distributions for human inspection.

ROADMAP Phase 1 MANUAL VALIDATION: "Generate 1 M transactions; inspect
distributions and a sample of each fraud pattern for plausibility."

Automated tests assert *relationships* -- peak beats trough, head beats median --
because pinning exact counts would fail on every legitimate tuning change. They
cannot judge whether the shapes look like card spending. That judgement is what
this tool exists to support, and it is the judgement every Phase 9 evidence
metric ultimately inherits: if the injected episodes are not plausible, the
causal keys describe something that does not happen.

Text tables, no plotting dependency: a chart nobody can read in a terminal or a
CI log is not inspection.
"""

from __future__ import annotations

import argparse
import collections
import math
import sys
from collections.abc import Mapping
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "packages"))


def _bar(value: float, peak: float, width: int = 38) -> str:
    filled = 0 if peak <= 0 else max(1, round(width * value / peak)) if value else 0
    return "#" * filled


def _histogram(title: str, counts: Mapping[Any, int], note: str = "") -> list[str]:
    if not counts:
        return [f"### {title}", "", "_no rows_", ""]
    peak = max(counts.values())
    total = sum(counts.values())
    lines = [f"### {title}", ""]
    if note:
        lines += [note, ""]
    lines += ["```"]
    for key in sorted(counts, key=str):
        value = counts[key]
        lines.append(f"{key!s:>22}  {value:>9,}  {value / total:6.2%}  {_bar(value, peak)}")
    lines += ["```", ""]
    return lines


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("dataset", type=Path, help="directory holding *.parquet")
    parser.add_argument("--out", type=Path, default=None, help="write markdown here")
    parser.add_argument("--samples", type=int, default=3, help="episodes to print per pattern")
    args = parser.parse_args()

    import pyarrow.parquet as pq

    transactions = args.dataset / "tx.raw.v1.parquet"
    if not transactions.is_file():
        print(f"no tx.raw.v1.parquet in {args.dataset}", file=sys.stderr)
        return 1

    table = pq.read_table(transactions)
    envelopes = table.column("envelope").to_pylist()
    payloads = table.column("payload").to_pylist()
    rows = len(payloads)

    hours: collections.Counter[int] = collections.Counter()
    weekdays: collections.Counter[str] = collections.Counter()
    merchants: collections.Counter[str] = collections.Counter()
    mccs: collections.Counter[str] = collections.Counter()
    channels: collections.Counter[str] = collections.Counter()
    countries: collections.Counter[str] = collections.Counter()
    accounts: collections.Counter[str] = collections.Counter()
    amounts: list[int] = []
    magnitudes: collections.Counter[str] = collections.Counter()

    import datetime as dt

    weekday_names = ("Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun")
    for envelope, payload in zip(envelopes, payloads, strict=True):
        occurred = dt.datetime.fromisoformat(envelope["occurred_at"].replace("Z", "+00:00"))
        hours[occurred.hour] += 1
        weekdays[f"{occurred.weekday()} {weekday_names[occurred.weekday()]}"] += 1
        merchants[payload["merchant_id"]] += 1
        mccs[payload["merchant_mcc"]] += 1
        channels[payload["channel"]] += 1
        countries[payload["merchant_country"]] += 1
        accounts[payload["account_id"]] += 1
        amount = payload["amount_minor"]
        amounts.append(amount)
        magnitudes[f"1e{int(math.log10(max(1, amount)))}"] += 1

    amounts.sort()

    def percentile(fraction: float) -> int:
        return amounts[min(len(amounts) - 1, int(len(amounts) * fraction))]

    lines: list[str] = [
        f"# Dataset inspection — `{args.dataset.name}`",
        "",
        "> Generated by `scripts/inspect_dataset.py` for the ROADMAP Phase 1 manual",
        "> validation step. Distribution *shape* is what matters here; the automated",
        "> tests assert the relationships, and a human judges plausibility.",
        "",
        f"- transactions: **{rows:,}**",
        f"- distinct accounts appearing: **{len(accounts):,}**",
        f"- distinct merchants appearing: **{len(merchants):,}**",
        "",
        "## Amounts (minor units)",
        "",
        "```",
        f"  min {amounts[0]:>12,}",
        f"  p25 {percentile(0.25):>12,}",
        f"  p50 {percentile(0.50):>12,}",
        f"  p75 {percentile(0.75):>12,}",
        f"  p95 {percentile(0.95):>12,}",
        f"  p99 {percentile(0.99):>12,}",
        f"  max {amounts[-1]:>12,}",
        "```",
        "",
    ]
    lines += _histogram(
        "Amount order of magnitude",
        dict(magnitudes),
        "A long right tail is what makes 'anomalously high value' a statement about a "
        "distribution rather than a threshold someone picked.",
    )
    lines += _histogram(
        "Hour of day (UTC)",
        {f"{h:02d}:00": c for h, c in sorted(hours.items())},
        "A real overnight trough matters: a velocity burst at 04:00 means something "
        "different from the same burst at 13:00, and that only holds if the baseline dips.",
    )
    lines += _histogram("Day of week", dict(weekdays))
    lines += _histogram("Channel", dict(channels))
    lines += _histogram("Merchant country", dict(countries))
    lines += _histogram(
        "Top 15 MCCs",
        dict(collections.Counter(mccs).most_common(15)),
        "Everyday spend should dominate, with high-risk categories present but not common.",
    )

    ranked = merchants.most_common()
    head = sum(c for _, c in ranked[: max(1, len(ranked) // 100)])
    lines += [
        "### Merchant concentration",
        "",
        "Uniform merchants would make merchant-risk aggregates and MCC baselines",
        "meaningless, and the collusion scenario needs an outlier visible against a baseline.",
        "",
        "```",
        f"  busiest merchant     {ranked[0][1]:>9,} transactions",
        f"  median merchant      {ranked[len(ranked) // 2][1]:>9,}",
        f"  quietest merchant    {ranked[-1][1]:>9,}",
        f"  top 1% of merchants  {head / rows:>9.1%} of all volume",
        "```",
        "",
    ]

    for topic in ("identity.events.v1", "device.events.v1"):
        path = args.dataset / f"{topic}.parquet"
        if path.is_file():
            side = pq.read_table(path)
            kinds: collections.Counter[str] = collections.Counter()
            for payload in side.column("payload").to_pylist():
                kinds[payload.get("identity_event_type") or payload.get("device_event_type")] += 1
            lines += _histogram(f"`{topic}` ({side.num_rows:,} rows)", dict(kinds))

    report = "\n".join(lines)
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(report + "\n")
        print(f"wrote {args.out}")
    else:
        print(report)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
