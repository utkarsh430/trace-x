"""The layout benchmark's markdown report, rendered from its run record alone.

Every section heading names the run's `run_id`, so `make check-claims` resolves every number
beneath it. Nothing here names a winner: the ranking is the one `spec.rank` computed from the
measurements under the rule declared before the run, and is printed as computed.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from typing import Any, Final

MIB: Final = 1024 * 1024

CAVEAT: Final = (
    "> Synthetic rows shaped like `gold.observations`, generated and measured on one laptop with "
    "local open-source Delta 4.0.1. The ranking applies to the local lake only: it says nothing "
    "about Databricks, where ADR-0015 decides separately, and nothing about fraud-detection "
    "performance."
)


def _mib(value: float) -> str:
    return f"{value / MIB:,.1f} MiB"


def _count(value: float) -> str:
    return f"{value:,.0f}" if float(value).is_integer() else f"{value:,.1f}"


def _table(header: Sequence[str], rows: Sequence[Sequence[str]]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(row) + " |" for row in rows]
    return out


def render(record: Mapping[str, Any]) -> str:
    run_id = str(record["run_id"])
    measured: Mapping[str, Any] = record["measured"]
    session: Mapping[str, Any] = record["session"]
    toolchain: Mapping[str, Any] = record["toolchain"]
    shapes: Sequence[Mapping[str, Any]] = record["query_shapes"]
    variants: Sequence[Mapping[str, Any]] = record["variants"]
    reasons: Sequence[str] = record.get("unpublishable_reasons") or [
        "a smoke run, fewer than the required rows or repetitions, or a dirty worktree"
    ]
    status = "publishable" if record["publishable"] else f"NOT publishable ({'; '.join(reasons)})"
    lines = [
        "# Delta layout benchmark (ADR-0015, local)",
        "",
        f"Generated by `benchmarks/delta_layout/run.py` from the run recorded as "
        f"`run_id: {run_id}`, which `make check-claims` resolves. Status: **{status}**.",
        "",
        CAVEAT,
        "",
        f"## Configuration — `run_id: {run_id}`",
        "",
        *_table(
            ["Setting", "Value"],
            [
                ["mode", str(record["mode"])],
                ["rows", _count(record["row_count"])],
                ["seed", str(record["seed"])],
                ["generator", f"`{record['generator_version']}` `{record['generator_digest']}`"],
                ["dataset digest", f"`{record['dataset_digest']}`"],
                ["repetitions", str(session["reps"])],
                ["master", f"`{session['master']}`"],
                ["driver memory", f"`{session['driver_memory']}`"],
                ["shuffle partitions", str(session["shuffle_partitions"])],
                [
                    "toolchain",
                    ", ".join(f"{k} {toolchain[k]}" for k in sorted(toolchain)),
                ],
                ["git", f"`{record['git_commit_sha']}` dirty={record['dirty_worktree']}"],
            ],
        ),
        "",
        "Spark and Delta settings the layouts depend on (ADR-0048 correction 5):",
        "",
        *_table(
            ["Key", "Value"],
            [[f"`{k}`", f"`{v}`"] for k, v in sorted(record["spark_conf"].items())],
        ),
        "",
        f"## Declared before measurement — `run_id: {run_id}`",
        "",
        f"**Ranking rule.** {record['ranking_rule']}",
        "",
        f"**Warm and cold.** {record['warm_cold_policy']}",
        "",
        "**Query shapes.**",
        "",
        *_table(
            ["Shape", "Provenance", "Source"],
            [[f"`{s['name']}`", str(s["provenance"]), str(s["source"])] for s in shapes],
        ),
        "",
        "**Layouts.**",
        "",
        *_table(
            ["Variant", "Layout"],
            [[f"`{v['name']}`", str(v["description"])] for v in variants],
        ),
        "",
    ]

    builds: Sequence[Mapping[str, Any]] = measured["builds"]
    lines += [
        f"## Tables as built — `run_id: {run_id}`",
        "",
        "Files and sizes from the Delta snapshot after the build; write is the MERGE Gold's "
        "writer issues, optimize the variant's `OPTIMIZE`.",
        "",
        *_table(
            [
                "Variant",
                "Files",
                "Size",
                "Smallest file",
                "Median file",
                "Largest file",
                "Partitions",
                "Protocol",
                "Write s",
                "OPTIMIZE s",
            ],
            [
                [
                    f"`{b['variant']}`",
                    _count(b["num_files"]),
                    _mib(b["size_bytes"]),
                    _mib(b["file_bytes_min"]),
                    _mib(b["file_bytes_median"]),
                    _mib(b["file_bytes_max"]),
                    _count(b["partitions"]),
                    f"({b['min_reader_version']}, {b['min_writer_version']}) "
                    + ", ".join(b["table_features"]),
                    f"{b['write_s']:.1f}",
                    "-" if b["optimize_s"] is None else f"{b['optimize_s']:.1f}",
                ]
                for b in builds
            ],
        ),
        "",
    ]

    summaries = {(s["variant"], s["shape"]): s for s in measured["summaries"]}
    variant_names = [v["name"] for v in variants]
    for shape in shapes:
        name = str(shape["name"])
        lines += [
            f"## Shape `{name}` — `run_id: {run_id}`",
            "",
            f"{shape['description']} ({shape['provenance']}). Medians over "
            f"{session['reps']} repetitions; the rows every layout returned are identical.",
            "",
            *_table(
                [
                    "Variant",
                    "Rows",
                    "Files selected",
                    "Bytes selected",
                    "Bytes read",
                    "Records read",
                    "Wall s (median)",
                    "Wall s (min-max)",
                ],
                [
                    [
                        f"`{v}`",
                        _count(c["rows_median"]),
                        _count(c["selected_files"]),
                        _mib(c["selected_bytes"]),
                        _mib(c["input_bytes"]),
                        _count(c["input_records"]),
                        f"{c['wall_median_s']:.3f}",
                        f"{c['wall_min_s']:.3f}-{c['wall_max_s']:.3f}",
                    ]
                    for v in variant_names
                    for c in [summaries[(v, name)]]
                ],
            ),
            "",
            "Order on this shape (bytes read, then files, then wall): "
            + ", ".join(f"`{v}`" for v in measured["shape_leaders"][name]),
            "",
        ]

    shape_names = [str(s["name"]) for s in shapes]
    lines += [
        f"## Ranking — `run_id: {run_id}`",
        "",
        "Computed by `spec.rank` under the rule above. Ratios are to `control`; below 1 is better.",
        "",
        *_table(
            [
                "Rank",
                "Variant",
                "Bytes-read score",
                "Files score",
                "Wall score",
                *[f"`{s}` bytes ratio" for s in shape_names],
            ],
            [
                [
                    str(r["rank"]),
                    f"`{r['variant']}`",
                    f"{r['bytes_score']:.3f}",
                    f"{r['files_score']:.3f}",
                    f"{r['wall_score']:.3f}",
                    *[f"{r['ratios'][s]['bytes']:.3f}" for s in shape_names],
                ]
                for r in measured["ranking"]
            ],
        ),
        "",
        "Machine-readable results: " + f"`benchmarks/delta_layout/results/{run_id}.json`.",
        "",
    ]
    return "\n".join(lines)


__all__ = ["CAVEAT", "render"]
